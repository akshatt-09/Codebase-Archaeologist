import os
import hashlib


class DuplicationDetector:
    BLOCK_SIZE = 6
    EXCLUDED_PARTS = {"vendor", "third_party", "third-party", "generated", "autogenerated"}
    EXCLUDED_NAMES = {"package-lock.json", "yarn.lock", "pnpm-lock.yaml", "poetry.lock", "composer.lock", "cargo.lock"}
    SUPPORTED_EXTENSIONS = {".py", ".js", ".jsx", ".ts", ".tsx", ".java", ".css", ".scss", ".html", ".sql"}

    @classmethod
    def _is_generated_or_vendor(cls, record: dict) -> bool:
        path = record.get("path", "").replace("\\", "/").lower()
        basename = os.path.basename(path)
        if basename in cls.EXCLUDED_NAMES or basename.endswith((".min.js", ".min.css", ".min.map")):
            return True
        if os.path.splitext(basename)[1] not in cls.SUPPORTED_EXTENSIONS:
            return True
        if any(part in cls.EXCLUDED_PARTS for part in path.split("/")):
            return True
        absolute_path = record.get("absolute_path")
        if absolute_path and os.path.isfile(absolute_path):
            try:
                with open(absolute_path, "r", encoding="utf-8", errors="ignore") as source:
                    header = "\n".join(source.readline() for _ in range(5)).lower()
                if "@generated" in header or "generated by" in header or "do not edit" in header:
                    return True
            except OSError:
                pass
        return False

    @staticmethod
    def _normalized_lines(absolute_path: str):
        lines = []
        with open(absolute_path, "r", encoding="utf-8", errors="ignore") as source:
            for line_number, raw_line in enumerate(source, 1):
                value = raw_line.strip()
                if value.startswith(("#", "//", "/*", "*")):
                    value = ""
                lines.append((line_number, value))
        return lines

    @classmethod
    def analyze(cls, file_records: list[dict]) -> dict:
        eligible_records = [record for record in file_records if not cls._is_generated_or_vendor(record)]
        block_hashes = {}
        duplicated_blocks = []
        total_loc = sum(record.get("lines", 0) for record in eligible_records)

        if total_loc < cls.BLOCK_SIZE:
            return {"percentage": "Not available", "duplicatedBlocks": [], "method": "Six-line normalized source blocks; generated/vendor files excluded."}

        for record in eligible_records:
            path = record.get("absolute_path")
            if not path or not os.path.isfile(path):
                continue
            try:
                lines = cls._normalized_lines(path)
                for index in range(len(lines) - cls.BLOCK_SIZE + 1):
                    block = lines[index:index + cls.BLOCK_SIZE]
                    nonempty_count = sum(1 for _, text in block if text)
                    if nonempty_count < cls.BLOCK_SIZE:
                        continue
                    block_text = "\n".join(text for _, text in block)
                    digest = hashlib.sha256(block_text.encode("utf-8")).hexdigest()
                    block_hashes.setdefault(digest, []).append({
                        "file": record["path"],
                        "line": block[0][0],
                        "endLine": block[-1][0],
                        "nonemptyLines": nonempty_count,
                    })
            except OSError:
                continue

        duplicated_locations = set()
        for occurrences in block_hashes.values():
            if len(occurrences) > 1:
                for duplicate in occurrences[1:]:
                    duplicated_locations.update((duplicate["file"], line_number) for line_number in range(duplicate["line"], duplicate["endLine"] + 1))
                duplicated_blocks.append({"occurrences": [
                    {"file": item["file"], "line": item["line"], "endLine": item["endLine"]}
                    for item in occurrences
                ]})

        duplicated_lines_count = len(duplicated_locations)
        percentage = min(100.0, round((duplicated_lines_count / total_loc) * 100, 2)) if total_loc > 0 else 0
        return {
            "percentage": percentage,
            "duplicatedBlocks": duplicated_blocks[:15],
            "method": "Six-line normalized source blocks; generated/vendor files excluded; comments are normalized while source line locations are preserved.",
        }
